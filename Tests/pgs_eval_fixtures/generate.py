#!/usr/bin/env python3
"""Generate OLS reference values for adjutant_pgs_eval_test.

Run once; the output is committed.  Neither Python nor statsmodels is needed
to build or run adjutant, or to run pgs_eval_check.sh.

    python3 Tests/pgs_eval_fixtures/generate.py > Tests/pgs_eval_fixtures/ols_reference.txt

This overwrites the file, so the confidence-interval keys generate_ci.R adds go
with it.  Re-run `Rscript Tests/pgs_eval_fixtures/generate_ci.R` afterwards.
"""
import numpy as np
import statsmodels.api as sm

rng = np.random.default_rng(20260731)
n, n_covar = 200, 3

y = rng.normal(size=n)
covars = rng.normal(size=(n, n_covar))
pgs = rng.normal(size=n)
# Make the PGS genuinely predictive so the test is not all noise.
y += 0.45 * pgs + 0.3 * covars[:, 0]

X_null = sm.add_constant(covars)
X_full = np.column_stack([X_null, (pgs - pgs.mean()) / pgs.std(ddof=1)])

null = sm.OLS(y, X_null).fit()
full = sm.OLS(y, X_full).fit()

print("# adjutant_pgs_eval OLS reference -- generated by generate.py, do not edit")
print(f"n {n}")
print(f"n_covar {n_covar}")
print(f"beta {full.params[-1]:.17g}")
print(f"se {full.bse[-1]:.17g}")
print(f"pval {full.pvalues[-1]:.17g}")
print(f"r2_null {null.rsquared:.17g}")
print(f"r2_full {full.rsquared:.17g}")
print(f"r2_incr {full.rsquared - null.rsquared:.17g}")
print("# data: y then n_covar covariate columns then pgs, one sample per line")
for i in range(n):
    row = [y[i]] + list(covars[i]) + [pgs[i]]
    print(" ".join(f"{v:.17g}" for v in row))
